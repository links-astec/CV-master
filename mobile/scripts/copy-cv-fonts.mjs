// Copies the CV fonts from the website's packages into the app, so CV previews work offline,
// and writes src/lib/cvFontFiles.ts (which file is which family, weight and style).
// The list matches the server's PDF fonts (craftcv/server/index.js, loadFontFaces).
//   node scripts/copy-cv-fonts.mjs
import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const src = path.join(root, '..', 'craftcv', 'node_modules', '@fontsource')
const out = path.join(root, 'assets', 'cv-fonts')

// [package, family, weights, italic weights]
const FAMILIES = [
  ['dm-sans', 'DM Sans', [300, 400, 500, 600, 700], [400]],
  ['dm-serif-display', 'DM Serif Display', [400], [400]],
  ['inter', 'Inter', [400, 500, 600, 700], []],
  ['lora', 'Lora', [400, 500, 600, 700], [400]],
  ['playfair-display', 'Playfair Display', [400, 600, 700, 900], []],
  ['space-grotesk', 'Space Grotesk', [400, 500, 700], []],
  ['outfit', 'Outfit', [200, 300, 400, 500, 600, 700], []],
  ['eb-garamond', 'EB Garamond', [400, 500, 600], []],
  ['manrope', 'Manrope', [400, 600, 700, 800], []],
  ['ibm-plex-mono', 'IBM Plex Mono', [400, 500], []],
]

fs.mkdirSync(out, { recursive: true })
const lines = []
let n = 0
for (const [pkg, family, weights, italics] of FAMILIES) {
  const faces = []
  for (const [w, style] of [...weights.map(w => [w, 'normal']), ...italics.map(w => [w, 'italic'])]) {
    const name = `${pkg}-latin-${w}-${style}.woff2`
    const from = path.join(src, pkg, 'files', name)
    if (!fs.existsSync(from)) { console.warn('missing', name); continue }
    fs.copyFileSync(from, path.join(out, name))
    faces.push(`    { weight: ${w}, style: '${style}', file: require('../../assets/cv-fonts/${name}') },`)
    n++
  }
  lines.push(`  '${family}': [\n${faces.join('\n')}\n  ],`)
}

fs.writeFileSync(path.join(root, 'src', 'lib', 'cvFontFiles.ts'), `// Generated by scripts/copy-cv-fonts.mjs. Do not edit by hand.
/* eslint-disable @typescript-eslint/no-require-imports -- require() is how Metro bundles font files */
export type FontFace = { weight: number; style: 'normal' | 'italic'; file: number }
export const CV_FONT_FILES: Record<string, FontFace[]> = {
${lines.join('\n')}
}
`)
console.log(`copied ${n} font files to assets/cv-fonts`)
